# urn:miot-spec-v2:property:left-time:0000003C:xiaomi-s2:1  -> "left-time"
_URN_PART = re.compile(r"^urn:[^:]+:([^:]+):([^:]+):([^:]+):([^:]+):([^:]+)$")

# format -> widget kind the renderer knows how to draw
WIDGET_BY_FORMAT = {
    "bool": "switch",
    "uint8": "number",
    "uint16": "number",
    "uint32": "number",
    "int8": "number",
    "int16": "number",
    "int32": "number",
    "int64": "number",
    "uint64": "number",
    "float": "number",
    "string": "text",
}

_WRITE_ACCESS = "write"
_NOTIFY_ACCESS = "notify"
_READ_ACCESS = "read"


def urn_of(urn, index=2):
    """Return one colon-separated field of a urn, or ``""``."""
    if not urn:
        return ""
    parts = urn.split(":")
    return parts[index] if len(parts) > index else ""


def short_name(urn):
    """``urn:miot-spec-v2:property:left-time:...`` -> ``left-time``."""
    return urn_of(urn, 3)


class ValueOption:
    """One entry of a ``value-list`` (an enum value)."""

    __slots__ = ("value", "name", "label")

    def __init__(self, value, name, label):
        self.value = value
        self.name = name
        self.label = label

    def __repr__(self):
        return "<ValueOption %r %r>" % (self.value, self.label)


class Property:
    """A spec property (readable / writable / notifiable value)."""

    __slots__ = ("siid", "piid", "type", "name", "label", "description",
                 "format", "access", "unit", "value_range", "value_list",
                 "gatt_access")

    def __init__(self, siid, piid, type_, name, label, description, format_,
                 access, unit, value_range, value_list, gatt_access):
        self.siid = siid
        self.piid = piid
        self.type = type_
        self.name = name
        self.label = label
        self.description = description
        self.format = format_
        self.access = access
        self.unit = unit
        self.value_range = value_range      # (min, max, step) or None
        self.value_list = value_list        # tuple[ValueOption] or None
        self.gatt_access = gatt_access

    # -- capability ---------------------------------------------------
    @property
    def readable(self):
        return _READ_ACCESS in self.access

    @property
    def writable(self):
        return _WRITE_ACCESS in self.access

    @property
    def notifiable(self):
        return _NOTIFY_ACCESS in self.access

    @property
    def widget(self):
        """Coarse widget kind; the UI layer refines it with card config."""
        if self.value_list:
            return "enum"
        return WIDGET_BY_FORMAT.get(self.format, "text")

    # -- value helpers ------------------------------------------------
    def label_for(self, value):
        """Human label for an enum value, else ``str(value)``."""
        if self.value_list:
            for option in self.value_list:
                if option.value == value:
                    return option.label
        return "%s" % (value,)

    def coerce(self, value):
        """Best-effort conversion of a JSON value to this property's format."""
        fmt = self.format
        if fmt == "bool":
            if isinstance(value, bool):
                return value
            if isinstance(value, (int, float)):
                return bool(value)
            if isinstance(value, str):
                return value.strip().lower() in ("1", "true", "on", "yes")
            return bool(value)
        if fmt.startswith(("uint", "int")):
            return int(value)
        if fmt == "float":
            return float(value)
        if fmt == "string":
            if isinstance(value, bytes):
                return value.decode("utf-8", "replace")
            return "%s" % (value,)
        return value

    def clamp(self, value):
        """Clamp a numeric value into ``value-range`` when one is declared."""
        if not self.value_range:
            return value
        low, high = self.value_range[0], self.value_range[1]
        step = self.value_range[2] if len(self.value_range) > 2 else 0
        if step:
            value = low + int(round(float(value - low) / step)) * step
        return max(low, min(high, value))

    def accepts(self, value):
        """Cheap client-side validation against the spec."""
        if self.value_list:
            return any(option.value == value for option in self.value_list)
        if self.value_range and isinstance(value, (int, float)):
            low, high = self.value_range[0], self.value_range[1]
            return low <= value <= high
        return True

    def to_dict(self):
        return {
            "siid": self.siid, "piid": self.piid, "type": self.type,
            "name": self.name, "label": self.label, "description": self.description,
            "format": self.format, "access": list(self.access), "unit": self.unit,
            "value_range": list(self.value_range) if self.value_range else None,
            "value_list": [[o.value, o.name, o.label] for o in self.value_list]
            if self.value_list else None,
            "widget": self.widget,
        }

    def __repr__(self):
        return "<Property %d.%d %s %s>" % (self.siid, self.piid, self.name, self.format)


class _Arg:
    """An action/event argument.

    Two shapes occur in published specs: an inline object with format/range
    information, or a bare integer referencing another iid.  Both must parse.
    """

    __slots__ = ("piid", "type", "name", "label", "format", "value_list",
                 "value_range", "unit", "inline")

    def __init__(self, data):
        if not isinstance(data, dict):
            # bare iid reference: no type/format information available
            self.piid = data if isinstance(data, int) else 0
            self.type = ""
            self.name = ""
            self.label = ""
            self.format = ""
            self.value_list = None
            self.value_range = None
            self.unit = None
            self.inline = False
            return
        self.piid = _iid(data, "piid")
        self.type = data.get("type", "")
        self.name = short_name(self.type)
        self.label = _label(data)
        self.format = data.get("format", "")
        self.value_list = _parse_value_list(data)
        self.value_range = _parse_value_range(data)
        self.unit = data.get("unit")
        self.inline = True

    def to_dict(self):
        return {"piid": self.piid, "type": self.type, "name": self.name,
                "label": self.label, "format": self.format,
                "inline": self.inline, "unit": self.unit,
                "value_range": list(self.value_range) if self.value_range else None,
                "value_list": [[o.value, o.name, o.label] for o in self.value_list]
                if self.value_list else None}


class Action:
    __slots__ = ("siid", "aiid", "type", "name", "label", "description", "in_args", "out_args")

    def __init__(self, siid, data):
        self.siid = siid
        self.aiid = _iid(data, "aiid")
        self.type = data.get("type", "")
        self.name = short_name(self.type)
        self.label = _label(data)
        self.description = data.get("description", "")
        self.in_args = tuple(_Arg(a) for a in data.get("in") or ())
        self.out_args = tuple(_Arg(a) for a in data.get("out") or ())

    def to_dict(self):
        return {"siid": self.siid, "aiid": self.aiid, "type": self.type,
                "name": self.name, "label": self.label,
                "in": [a.to_dict() for a in self.in_args],
                "out": [a.to_dict() for a in self.out_args]}

    def __repr__(self):
        return "<Action %d.%d %s>" % (self.siid, self.aiid, self.name)


class Event:
    __slots__ = ("siid", "eiid", "type", "name", "label", "description", "arguments")

    def __init__(self, siid, data):
        self.siid = siid
        self.eiid = _iid(data, "eiid")
        self.type = data.get("type", "")
        self.name = short_name(self.type)
        self.label = _label(data)
        self.description = data.get("description", "")
        self.arguments = tuple(_Arg(a) for a in data.get("arguments") or ())

    def to_dict(self):
        return {"siid": self.siid, "eiid": self.eiid, "type": self.type,
                "name": self.name, "label": self.label,
                "arguments": [a.to_dict() for a in self.arguments]}

    def __repr__(self):
        return "<Event %d.%d %s>" % (self.siid, self.eiid, self.name)


class Service:
    __slots__ = ("siid", "type", "name", "label", "description",
                 "properties", "actions", "events")

    def __init__(self, data):
        self.siid = _iid(data, "siid")
        self.type = data.get("type", "")
        self.name = short_name(self.type)
        self.label = _label(data)
        self.description = data.get("description", "")
        self.properties = tuple(
            _parse_property(self.siid, p) for p in data.get("properties") or ())
        self.actions = tuple(Action(self.siid, a) for a in data.get("actions") or ())
        self.events = tuple(Event(self.siid, e) for e in data.get("events") or ())

    def property(self, name_or_iid):
        for prop in self.properties:
            if prop.name == name_or_iid or prop.piid == name_or_iid:
                return prop
        return None

    def to_dict(self):
        return {
            "siid": self.siid, "type": self.type, "name": self.name,
            "label": self.label, "description": self.description,
            "properties": [p.to_dict() for p in self.properties],
            "actions": [a.to_dict() for a in self.actions],
            "events": [e.to_dict() for e in self.events],
        }

    def __repr__(self):
        return "<Service %d %s (%d props)>" % (self.siid, self.name, len(self.properties))


class Spec:
    """A parsed spec instance."""

    __slots__ = ("urn", "description", "comment", "services", "_index")

    def __init__(self, urn, description, comment, services):
        self.urn = urn
        self.description = description
        self.comment = comment
        self.services = tuple(services)
        self._index = {service.siid: service for service in self.services}

    # -- lookup --------------------------------------------------------
    @property
    def model(self):
        """``vendor-model`` part of the urn, e.g. ``xiaomi-s2``."""
        return urn_of(self.urn, 5)

    @property
    def device_type(self):
        """``urn:miot-spec-v2:device:dishwasher:...`` -> ``dishwasher``."""
        return urn_of(self.urn, 3)

    def service(self, name_or_iid):
        for svc in self.services:
            if svc.name == name_or_iid or svc.siid == name_or_iid:
                return svc
        if isinstance(name_or_iid, int):
            return self._index.get(name_or_iid)
        return None

    def property(self, siid, piid):
        svc = self._index.get(siid)
        return svc.property(piid) if svc else None

    def find_property(self, service_name, property_name):
        svc = self.service(service_name)
        return svc.property(property_name) if svc else None

    # -- flattened views ----------------------------------------------
    def all_properties(self):
        for svc in self.services:
            yield from svc.properties

    def writable_properties(self):
        return [p for p in self.all_properties() if p.writable]

    def readable_properties(self):
        return [p for p in self.all_properties() if p.readable]

    def notifiable_properties(self):
        return [p for p in self.all_properties() if p.notifiable]

    def power_property(self):
        """The ``on`` bool most devices expose -- used for the probe matrix."""
        for svc in self.services:
            prop = svc.property("on")
            if prop is not None and prop.writable and prop.format == "bool":
                return prop
        return None

    def status_property(self):
        for svc in self.services:
            prop = svc.property("status")
            if prop is not None and prop.value_list:
                return prop
        return None

    def to_dict(self):
        return {"urn": self.urn, "description": self.description,
                "comment": self.comment,
                "services": [s.to_dict() for s in self.services]}

    def __repr__(self):
        return "<Spec %s %d services>" % (self.urn, len(self.services))


# --- helpers -----------------------------------------------------------

def _iid(data, *names):
    """Read an iid that may be named ``iid`` (wire) or e.g. ``siid`` (our dump)."""
    for name in names + ("iid",):
        value = data.get(name)
        if value:
            return value
    return 0


def _label(data):
    """Prefer the Chinese ``comment``, fall back to English ``description``.

    Some published specs embed stray newlines/tabs in these strings (e.g. the
    Yeelight scene properties), which used to break the UI layout, so the value
    is normalised to a single line.
    """
    for key in ("comment", "description"):
        raw = data.get(key) or ""
        cleaned = " ".join(raw.split())
        if cleaned:
            return cleaned
    return ""


def _parse_value_range(data):
    rng = data.get("value-range")
    if not rng:
        return None
    values = list(rng)
    while len(values) < 3:
        values.append(0)
    return tuple(values[:3])


def _parse_value_list(data):
    items = data.get("value-list")
    if not items:
        return None
    options = []
    for item in items:
        label = (item.get("comment") or "").strip() or (item.get("description") or "").strip()
        options.append(ValueOption(item.get("value"), item.get("description") or "", label))
    return tuple(options)


def _parse_property(siid, data):
    type_ = data.get("type", "")
    return Property(
        siid=siid,
        piid=_iid(data, "piid"),
        type_=type_,
        name=short_name(type_),
        label=_label(data),
        description=data.get("description", ""),
        format_=data.get("format", ""),
        access=tuple(data.get("access") or ()),
        unit=data.get("unit"),
        value_range=_parse_value_range(data),
        value_list=_parse_value_list(data),
        gatt_access=data.get("gatt-access"),
    )


def _synthesise_enum(labels, property_key):
    """Build a value-list from ``...:valuelist:NNN`` translation keys.

    Some specs declare a plain ``uint8`` with no value-list while the official
    translation table *does* enumerate it (health pot ``device mode``).  We map
    translation index -> value directly; the renderer adds a "current value"
    entry when the device reports something outside the list.
    """
    prefix = property_key + ":valuelist:"
    entries = []
    for key, value in labels.items():
        if not key.startswith(prefix):
            continue
        try:
            index = int(key[len(prefix):])
        except ValueError:
            continue
        entries.append((index, value))
    if not entries:
        return None
    entries.sort()
    options = []
    for index, label in entries:
        options.append(ValueOption(index, "", " ".join((label or "").split())))
    return tuple(options)


def parse_spec(payload):
    """Parse a raw spec instance dict into :class:`Spec`.

    Accepts both the wire shape (``type``) and our own ``to_dict`` output
    (``urn``) so specs can be round-tripped through the on-disk cache.
    """
    if not isinstance(payload, dict):
        raise ValueError("spec payload must be a dict")
    services = [Service(s) for s in payload.get("services") or ()]
    if not services:
        raise ValueError("spec has no services")
    return Spec(
        urn=payload.get("type") or payload.get("urn") or "",
        description=payload.get("description", ""),
        comment=payload.get("comment", ""),
        services=services,
    )


# --------------------------------------------------------------------------
# i18n (multiLanguage table)
# --------------------------------------------------------------------------

# GET https://miot-spec.org/instance/v2/multiLanguage?urn=<urn> answers
#   {"data": {"en": {...}, "zh_cn": {...}}, "timestamp": ...}
# with keys:
#   service:002
#   service:002:property:002
#   service:002:property:002:valuelist:000     <- index into value-list, 0-based
#   service:002:action:001
#   service:002:event:001
# Note ``valuelist`` is keyed by the **position** in value-list, not by the
# enum value, so we must map by index.
I18N_LANGUAGE_PREFERENCE = ("zh_cn", "zh_CN", "zh", "en")


def pick_language(table, preference=I18N_LANGUAGE_PREFERENCE):
    """Return the label dict for the best available language, or ``None``."""
    for language in preference:
        labels = table.get(language)
        if labels:
            return labels
    return None


def apply_i18n(spec, table, preference=I18N_LANGUAGE_PREFERENCE):
    """Overwrite human labels on ``spec`` from a multiLanguage table in place."""
    labels = pick_language(table, preference)
    if not labels:
        return spec

    def label(key, fallback):
        # The multiLanguage table is user-facing text exported from Mi Home and
        # does contain stray tabs/newlines (Yeelight scene properties), which
        # broke the layout, so collapse whitespace here as well.
        value = " ".join((labels.get(key) or "").split())
        if value:
            return value
        return " ".join((fallback or "").split())

    for service in spec.services:
        prefix = "service:%03d" % service.siid
        service.label = label(prefix, service.label)
        for prop in service.properties:
            pkey = "%s:property:%03d" % (prefix, prop.piid)
            prop.label = label(pkey, prop.label)
            if prop.value_list:
                options = []
                for index, option in enumerate(prop.value_list):
                    vkey = "%s:valuelist:%03d" % (pkey, index)
                    options.append(ValueOption(option.value, option.name,
                                               label(vkey, option.label)))
                prop.value_list = tuple(options)
            else:
                synthesised = _synthesise_enum(labels, pkey)
                if synthesised:
                    prop.value_list = synthesised
        for action in service.actions:
            action.label = label("%s:action:%03d" % (prefix, action.aiid), action.label)
        for event in service.events:
            event.label = label("%s:event:%03d" % (prefix, event.eiid), event.label)
    return spec
