"""MIoT spec (``urn:miot-spec-v2``) parsing into something a UI can drive.

Schema, verified against real instances fetched from
``https://miot-spec.org/miot-spec-v2/instance?type=<urn>``
(fixtures live in ``tests/fixtures/specs/``)::

    {type, description, comment,
     services: [ {iid, type, description, comment,
                  properties: [{iid, type, description, comment,
                                format, access, unit?, value-range?,
                                value-list?, gatt-access?}],
                  actions:    [{iid, type, description, comment, in?, out?}],
                  events:     [{iid, type, description, comment, arguments?}]}]}

Notes
-----
* ``iid`` **is** the siid / piid / aiid / eiid used on the wire.
* ``comment`` carries the Chinese human-readable name; ``description`` is
  English.  We prefer ``comment`` and fall back to ``description``.
* The spec says nothing about *when* a writable property is actually writable.
  That is why availability rules are generated by probing (see docs/03), not
  read from the spec.
"""
